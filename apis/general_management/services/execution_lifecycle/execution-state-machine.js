"use strict";

const EXECUTION_STATUS = Object.freeze({
  CREATED: "CREATED",
  QUEUED: "QUEUED",
  VALIDATING_PACKAGE: "VALIDATING_PACKAGE",
  CHECKING_RUNTIME: "CHECKING_RUNTIME",
  RECOVERING_RUNTIME: "RECOVERING_RUNTIME",
  READY: "READY",
  RUNNING: "RUNNING",
  COLLECTING_ARTIFACTS: "COLLECTING_ARTIFACTS",
  CLASSIFYING_FAILURE: "CLASSIFYING_FAILURE",
  REPAIR_PENDING: "REPAIR_PENDING",
  REPAIRING: "REPAIRING",
  RERUN_QUEUED: "RERUN_QUEUED",
  CANCEL_REQUESTED: "CANCEL_REQUESTED",
  PASSED: "PASSED",
  FAILED: "FAILED",
  BLOCKED: "BLOCKED",
  CANCELLED: "CANCELLED",
});

const TERMINAL_STATUSES = new Set([
  EXECUTION_STATUS.PASSED,
  EXECUTION_STATUS.FAILED,
  EXECUTION_STATUS.BLOCKED,
  EXECUTION_STATUS.CANCELLED,
]);

const TRANSITIONS = new Map([
  [EXECUTION_STATUS.CREATED, new Set([EXECUTION_STATUS.QUEUED, EXECUTION_STATUS.CANCEL_REQUESTED])],
  [EXECUTION_STATUS.QUEUED, new Set([EXECUTION_STATUS.VALIDATING_PACKAGE, EXECUTION_STATUS.CANCEL_REQUESTED])],
  [EXECUTION_STATUS.VALIDATING_PACKAGE, new Set([
    EXECUTION_STATUS.CHECKING_RUNTIME,
    EXECUTION_STATUS.FAILED,
    EXECUTION_STATUS.BLOCKED,
    EXECUTION_STATUS.CANCEL_REQUESTED,
  ])],
  [EXECUTION_STATUS.CHECKING_RUNTIME, new Set([
    EXECUTION_STATUS.RECOVERING_RUNTIME,
    EXECUTION_STATUS.READY,
    EXECUTION_STATUS.BLOCKED,
    EXECUTION_STATUS.CANCEL_REQUESTED,
  ])],
  [EXECUTION_STATUS.RECOVERING_RUNTIME, new Set([
    EXECUTION_STATUS.CHECKING_RUNTIME,
    EXECUTION_STATUS.READY,
    EXECUTION_STATUS.BLOCKED,
    EXECUTION_STATUS.CANCEL_REQUESTED,
  ])],
  [EXECUTION_STATUS.READY, new Set([EXECUTION_STATUS.RUNNING, EXECUTION_STATUS.CANCEL_REQUESTED])],
  [EXECUTION_STATUS.RUNNING, new Set([
    EXECUTION_STATUS.COLLECTING_ARTIFACTS,
    EXECUTION_STATUS.CLASSIFYING_FAILURE,
    EXECUTION_STATUS.CANCEL_REQUESTED,
  ])],
  [EXECUTION_STATUS.COLLECTING_ARTIFACTS, new Set([
    EXECUTION_STATUS.PASSED,
    EXECUTION_STATUS.CLASSIFYING_FAILURE,
    EXECUTION_STATUS.BLOCKED,
    EXECUTION_STATUS.CANCEL_REQUESTED,
  ])],
  [EXECUTION_STATUS.CLASSIFYING_FAILURE, new Set([
    EXECUTION_STATUS.REPAIR_PENDING,
    EXECUTION_STATUS.FAILED,
    EXECUTION_STATUS.BLOCKED,
    EXECUTION_STATUS.CANCEL_REQUESTED,
  ])],
  [EXECUTION_STATUS.REPAIR_PENDING, new Set([
    EXECUTION_STATUS.REPAIRING,
    EXECUTION_STATUS.FAILED,
    EXECUTION_STATUS.CANCEL_REQUESTED,
  ])],
  [EXECUTION_STATUS.REPAIRING, new Set([
    EXECUTION_STATUS.RERUN_QUEUED,
    EXECUTION_STATUS.FAILED,
    EXECUTION_STATUS.CANCEL_REQUESTED,
  ])],
  [EXECUTION_STATUS.RERUN_QUEUED, new Set([
    EXECUTION_STATUS.VALIDATING_PACKAGE,
    EXECUTION_STATUS.CANCEL_REQUESTED,
  ])],
  [EXECUTION_STATUS.CANCEL_REQUESTED, new Set([
    EXECUTION_STATUS.CANCELLED,
    EXECUTION_STATUS.FAILED,
  ])],
]);

class InvalidExecutionTransitionError extends Error {
  constructor(from, to) {
    super(`Invalid execution state transition: ${from} -> ${to}`);
    this.name = "InvalidExecutionTransitionError";
    this.code = "INVALID_EXECUTION_TRANSITION";
    this.from = from;
    this.to = to;
  }
}

function isTerminal(status) {
  return TERMINAL_STATUSES.has(status);
}

function canTransition(from, to) {
  if (from === to) return true;
  if (isTerminal(from)) return false;
  return Boolean(TRANSITIONS.get(from)?.has(to));
}

function assertTransition(from, to) {
  if (!canTransition(from, to)) {
    throw new InvalidExecutionTransitionError(from, to);
  }
}

module.exports = {
  EXECUTION_STATUS,
  TERMINAL_STATUSES,
  TRANSITIONS,
  InvalidExecutionTransitionError,
  isTerminal,
  canTransition,
  assertTransition,
};
