  execution_run_id VARCHAR(64) NOT NULL,
  root_execution_run_id VARCHAR(64) NOT NULL,
  rerun_execution_run_id VARCHAR(64) NULL,
  requirement_id VARCHAR(64) NULL,
  test_scenario_id VARCHAR(64) NULL,
  test_case_id VARCHAR(64) NULL,
  test_script_id VARCHAR(64) NULL,
  classification VARCHAR(64) NOT NULL,
  severity VARCHAR(32) NOT NULL DEFAULT 'MEDIUM',
  status VARCHAR(32) NOT NULL DEFAULT 'OPEN',
  title VARCHAR(512) NOT NULL,
  description TEXT NULL,
  expected_result TEXT NULL,
  actual_result TEXT NULL,
  assigned_to VARCHAR(100) NULL,
  product_repository VARCHAR(512) NULL,
  product_commit VARCHAR(128) NULL,
  product_pull_request VARCHAR(512) NULL,
  resolution TEXT NULL,
  resolved_at DATETIME(3) NULL,
  created_by VARCHAR(100) NULL,
  created_date DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  modified_by VARCHAR(100) NULL,
  modified_date DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
